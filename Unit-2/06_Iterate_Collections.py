
# Iterate over a list
print("List:")
fruits = ["Apple", "Banana", "Mango"]

for fruit in fruits:
    print(fruit)

# Iterate over a string
print("\nString:")
word = "PYTHON"

for character in word:
    print(character)

# Iterate over a dictionary
print("\nDictionary:")
student = {
    "name": "Heet",
    "age": 22,
    "course": "MCA"
}

for key, value in student.items():
    print(key, ":", value)
