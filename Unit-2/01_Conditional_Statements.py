# Program to demonstrate conditional statements

# 1. if statement
age = 22

if age >= 18:
    print("You are an adult.")

# 2. if-else statement
number = 7

if number % 2 == 0:
    print("Even number")
else:
    print("Odd number")

# 3. if-elif-else statement
marks = 85

if marks >= 90:
    print("Grade A")
elif marks >= 75:
    print("Grade B")
else:
    print("Grade C")
